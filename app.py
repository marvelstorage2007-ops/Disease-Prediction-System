# Load trained model and supporting files
model = joblib.load("random_forest_model.pkl")
encoder = joblib.load("label_encoder.pkl")
symptom_columns = joblib.load("symptom_columns.pkl")


# Dashboard heading
st.title("Disease Prediction System")

st.write(
    "A machine learning based system "
    "for symptom-based disease prediction."
)

# Model information
st.subheader("Model Information")

col1, col2 = st.columns(2)

with col1:
    st.metric("ML Algorithm", "Random Forest")

with col2:
    st.metric("Available Diseases", len(encoder.classes_))

st.markdown("""
<div class="info-box">
    Random Forest model loaded successfully.
</div>
""", unsafe_allow_html=True)


# Symptom selection
st.subheader("Select Your Symptoms")

st.write("Choose the symptoms you are experiencing.")

selected_symptoms = st.multiselect(
    "Symptoms",
    options=symptom_columns,
    format_func=lambda symptom: symptom.replace("_", " ").title(),
    placeholder="Search and select symptoms"
)


# Show selected symptoms
if selected_symptoms:
    st.write("Selected Symptoms:")

    for symptom in selected_symptoms:
        st.write("-", symptom.replace("_", " ").title())

else:
    st.write("No symptoms selected.")


# Predict disease
if st.button("Predict Disease"):

    if len(selected_symptoms) == 0:

        st.markdown("""
        <div class="info-box">
            Please select at least one symptom.
        </div>
        """, unsafe_allow_html=True)

    else:
        # Create input data
        input_data = pd.DataFrame(
            0,
            index=[0],
            columns=symptom_columns
        )

        # Mark selected symptoms as 1
        for symptom in selected_symptoms:
            input_data.loc[0, symptom] = 1

        # Make prediction
        prediction = model.predict(input_data)[0]

        predicted_disease = encoder.inverse_transform(
            [prediction]
        )[0]

        # Get model probability
        probabilities = model.predict_proba(input_data)[0]
        confidence = max(probabilities) * 100

        # Display result
        st.subheader("Prediction Result")

        st.markdown(f"""
        <div class="result-box">
            <b>Predicted Disease:</b>
            <h3>{predicted_disease}</h3>
            <b>Model Score:</b> {confidence:.2f}%
        </div>
        """, unsafe_allow_html=True)

        st.markdown("""
        <div class="info-box">
            This prediction is generated by a machine learning model
            and should not be considered a medical diagnosis.
        </div>
        """, unsafe_allow_html=True)
